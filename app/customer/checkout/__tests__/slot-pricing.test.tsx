import React,{act} from "react";
import {beforeAll,expect,it,vi} from "vitest";
import {installTestDom,findElements} from "@/components/shared/__tests__/render-test-dom";
import type {BookingSlot,CartItem,Activity} from "@/backend/core/types";
import {cartTotals} from "@/backend/core/helpers";
const state=vi.hoisted(()=>({slots:vi.fn(),activity:{id:"p",outletId:"o",price:0,name:"Slot product",variants:[{id:"v",priceDelta:0,label:"Standard"}],requiresBooking:true} as Activity}));
const item:CartItem={activityId:"p",variantId:"v",outletId:"o",slotId:"s",qty:2};
vi.mock("next/navigation",()=>({useRouter:()=>({push:vi.fn()})}));
vi.mock("next/link",()=>({default:({children,...props}:React.AnchorHTMLAttributes<HTMLAnchorElement>)=><a {...props}>{children}</a>}));
vi.mock("react-i18next",()=>({useTranslation:()=>({t:(key:string)=>key})}));
vi.mock("@/components/providers/auth",()=>({useAuth:()=>({currentUser:{id:"u"},capabilities:{checkout:{allowed:true}}})}));
vi.mock("@/components/providers/reference-currency",()=>({useReferenceCurrency:()=>({currency:"MYR",snapshot:{date:"today"}})}));
vi.mock("@/components/shared/reference-price",()=>({ReferencePrice:({amountMYR}:{amountMYR:number})=><span>RM{amountMYR.toFixed(2)}</span>}));
vi.mock("@/components/customer/use-customer-capability-gate",()=>({useCustomerCapabilityGate:()=>()=>true}));
vi.mock("@/backend/domains/catalogue",()=>({getBookingSlots:state.slots,getOutlets:async()=>[],getVoucherByCode:async()=>undefined}));
vi.mock("@/components/providers/cart",()=>({useCart:()=>({selectedItems:[item],selectedKeys:new Set(["p|v|s|o"]),activities:[state.activity],totals:(_voucher:unknown,prices?:Map<string,number>)=>cartTotals([{...item,priceOverride:prices?.get("s")}],[state.activity])})}));
import CheckoutPage from "../page";
let createRoot:typeof import("react-dom/client").createRoot;
let document:ReturnType<typeof installTestDom>;
beforeAll(async()=>{document=installTestDom();Object.assign(window,{location:{search:""}});({createRoot}=await import("react-dom/client"));});
it("waits for slot pricing and renders the same override in lines and totals",async()=>{
  vi.stubGlobal("fetch",vi.fn(async()=>new Response('{}',{status:500})));
  let complete!:(slots:BookingSlot[])=>void;state.slots.mockImplementation(()=>new Promise(resolve=>{complete=resolve;}));
  const container=document.createElement("div");const root=createRoot(container as unknown as Element);
  await act(async()=>root.render(<CheckoutPage/>));
  expect(container.textContent).not.toContain("ui.checkout.freeReservationTitle");
  const pay=findElements(container,element=>element.tagName === "BUTTON").at(-1)!;
  expect(pay.getAttribute("disabled")).not.toBeNull();
  await act(async()=>{complete([{id:"s",activityId:"p",outletId:"o",startsAt:"2030-10-01T00:00:00Z",capacity:10,booked:0,priceOverride:20}]);});
  expect(container.textContent.match(/RM40.00/g)?.length).toBeGreaterThanOrEqual(2);
  expect(container.textContent).toContain("ui.checkout.linePriceBreakdown");
  expect(container.textContent).toContain("RM20.00 × 2 = RM40.00");
  expect(container.textContent).not.toContain("ui.checkout.freeReservationTitle");
  await act(async()=>root.unmount());vi.unstubAllGlobals();
});
